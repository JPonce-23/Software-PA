        UPDATE asamblea a SET
            fecha_ingreso_ran=(SELECT min(e.fecha_evento) FROM tramite_ran_evento e JOIN catalogo_operativo c ON c.id_catalogo_opcion=e.id_tipo_evento WHERE e.id_tramite_ran=v_tramite.id_tramite_ran AND e.activo AND c.codigo IN ('ingreso','reingreso')),
