-- ---------------------------------------------------------------------------
-- Validaciones cruzadas de categorías, núcleos, contextos y objetivos.
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION fn_036_validar_catalogos_dominio()
RETURNS TRIGGER LANGUAGE plpgsql AS $fn$
DECLARE
    v_codigo TEXT;
    v_organo TEXT;
    v_cargo TEXT;
BEGIN
    IF TG_TABLE_NAME='nucleo_agrario' THEN
        IF NOT fn_036_opcion_catalogo_valida(NEW.id_tipo_tenencia,'tipo_tenencia') THEN
            RAISE EXCEPTION 'Tipo de tenencia inválido';
        END IF;
        SELECT codigo INTO v_codigo FROM catalogo_operativo WHERE id_catalogo_opcion=NEW.id_tipo_tenencia;
        NEW.tipo_nucleo := v_codigo;
    ELSIF TG_TABLE_NAME='proyecto_nucleo' THEN
        IF NOT fn_036_opcion_catalogo_valida(NEW.id_residencia,'residencia') THEN
            RAISE EXCEPTION 'Residencia inválida';
        END IF;
        IF NEW.id_residencia IS NOT NULL THEN
            SELECT nombre INTO NEW.residencia FROM catalogo_operativo WHERE id_catalogo_opcion=NEW.id_residencia;
        END IF;
    ELSIF TG_TABLE_NAME='orv' THEN
        IF NOT fn_036_opcion_catalogo_valida(NEW.id_estado_registral,'estado_registral_orv') THEN
            RAISE EXCEPTION 'Estado registral ORV inválido';
        END IF;
        IF NEW.id_estado_registral IS NOT NULL THEN
            SELECT codigo INTO v_codigo FROM catalogo_operativo WHERE id_catalogo_opcion=NEW.id_estado_registral;
            NEW.acta_eleccion_inscrita_ran := CASE WHEN v_codigo='inscrita' THEN TRUE WHEN v_codigo='no_ingresada' THEN FALSE ELSE NULL END;
        END IF;
    ELSIF TG_TABLE_NAME='orv_integrante' THEN
        IF NOT fn_036_opcion_catalogo_valida(NEW.id_organo,'organo_orv')
           OR NOT fn_036_opcion_catalogo_valida(NEW.id_cargo,'cargo_orv')
           OR NOT fn_036_opcion_catalogo_valida(NEW.id_calidad,'calidad_integrante_orv') THEN
            RAISE EXCEPTION 'Estructura ORV inválida';
        END IF;
        IF NEW.id_organo IS NOT NULL THEN
            SELECT codigo INTO v_organo FROM catalogo_operativo WHERE id_catalogo_opcion=NEW.id_organo;
            SELECT codigo INTO v_cargo FROM catalogo_operativo WHERE id_catalogo_opcion=NEW.id_cargo;
            IF (v_organo='comisariado' AND v_cargo NOT IN ('presidente','secretario','tesorero'))
               OR (v_organo='consejo_vigilancia' AND v_cargo NOT IN ('presidente','secretario_1','secretario_2')) THEN
                RAISE EXCEPTION 'Cargo % no pertenece al órgano %',v_cargo,v_organo;
            END IF;
        END IF;
    ELSIF TG_TABLE_NAME='bien_afectado' THEN
        IF NOT fn_036_opcion_catalogo_valida(NEW.id_tipo_gestion,'tipo_gestion')
           OR NOT fn_036_opcion_catalogo_valida(NEW.id_destino_superficie,'destino_superficie')
           OR NOT fn_036_opcion_catalogo_valida(NEW.id_tipo_cop_operativo,'tipo_cop_operativo') THEN
            RAISE EXCEPTION 'Catálogo de bien afectado inválido';
        END IF;
    ELSIF TG_TABLE_NAME='asamblea_convocatoria' THEN
        IF NOT fn_036_opcion_catalogo_valida(NEW.id_resultado,'resultado_convocatoria') THEN
            RAISE EXCEPTION 'Resultado de convocatoria inválido';
        END IF;
    ELSIF TG_TABLE_NAME='tramite_ran_evento' THEN
        IF NOT fn_036_opcion_catalogo_valida(NEW.id_tipo_evento,'tipo_evento_ran') THEN
            RAISE EXCEPTION 'Tipo de evento RAN inválido';
        END IF;
    ELSIF TG_TABLE_NAME='tramite_fifonafe_evento' THEN
        IF NOT fn_036_opcion_catalogo_valida(NEW.id_tipo_evento,'tipo_evento_fifonafe') THEN
            RAISE EXCEPTION 'Tipo de evento FIFONAFE inválido';
        END IF;
    ELSIF TG_TABLE_NAME='expediente_requisito' THEN
        IF NOT fn_036_opcion_catalogo_valida(NEW.id_estado,'estado_requisito_documental') THEN
            RAISE EXCEPTION 'Estado de requisito documental inválido';
        END IF;
    END IF;
    RETURN NEW;
END;
$fn$;

