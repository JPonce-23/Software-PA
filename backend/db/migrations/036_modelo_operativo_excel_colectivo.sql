            calificacion_registral_ran=(SELECT e.calificacion FROM tramite_ran_evento e JOIN catalogo_operativo c ON c.id_catalogo_opcion=e.id_tipo_evento WHERE e.id_tramite_ran=v_tramite.id_tramite_ran AND e.activo AND c.codigo='calificacion' ORDER BY e.ordinal DESC LIMIT 1),
            fecha_inscripcion_ran=(SELECT max(e.fecha_evento) FROM tramite_ran_evento e JOIN catalogo_operativo c ON c.id_catalogo_opcion=e.id_tipo_evento WHERE e.id_tramite_ran=v_tramite.id_tramite_ran AND e.activo AND c.codigo='inscripcion'),
            actualizado_en=now(), actualizado_por=NULLIF(current_setting('app.current_user_id',TRUE),'')::INTEGER
        WHERE a.id_asamblea=v_tramite.id_asamblea;
    ELSIF v_tramite.id_convenio IS NOT NULL THEN
        UPDATE convenio v SET
            ingreso_ran_fecha=(SELECT min(e.fecha_evento) FROM tramite_ran_evento e JOIN catalogo_operativo c ON c.id_catalogo_opcion=e.id_tipo_evento WHERE e.id_tramite_ran=v_tramite.id_tramite_ran AND e.activo AND c.codigo IN ('ingreso','reingreso')),
            numero_solicitud_ingreso=(SELECT e.numero_solicitud FROM tramite_ran_evento e JOIN catalogo_operativo c ON c.id_catalogo_opcion=e.id_tipo_evento WHERE e.id_tramite_ran=v_tramite.id_tramite_ran AND e.activo AND c.codigo IN ('ingreso','reingreso') AND e.numero_solicitud IS NOT NULL ORDER BY e.ordinal DESC LIMIT 1),
            calificacion_registral=(SELECT e.calificacion FROM tramite_ran_evento e JOIN catalogo_operativo c ON c.id_catalogo_opcion=e.id_tipo_evento WHERE e.id_tramite_ran=v_tramite.id_tramite_ran AND e.activo AND c.codigo='calificacion' ORDER BY e.ordinal DESC LIMIT 1),
            fecha_inscripcion_ran=(SELECT max(e.fecha_evento) FROM tramite_ran_evento e JOIN catalogo_operativo c ON c.id_catalogo_opcion=e.id_tipo_evento WHERE e.id_tramite_ran=v_tramite.id_tramite_ran AND e.activo AND c.codigo='inscripcion'),
