CREATE OR REPLACE FUNCTION fn_036_validar_bien_parcela()
RETURNS TRIGGER LANGUAGE plpgsql AS $fn$
DECLARE v_nucleo_bien INTEGER; v_nucleo_parcela INTEGER;
BEGIN
    IF NEW.id_parcela IS NOT NULL AND NEW.activo THEN
        SELECT pn.id_nucleo INTO v_nucleo_bien
        FROM afectacion a JOIN proyecto_nucleo pn ON pn.id_proyecto_nucleo=a.id_proyecto_nucleo
        WHERE a.id_afectacion=NEW.id_afectacion AND a.activo AND pn.activo;
        SELECT id_nucleo INTO v_nucleo_parcela FROM parcela WHERE id_parcela=NEW.id_parcela AND activo;
        IF v_nucleo_bien IS NULL OR v_nucleo_parcela IS NULL OR v_nucleo_bien<>v_nucleo_parcela THEN
            RAISE EXCEPTION 'La parcela del bien debe pertenecer al mismo núcleo';
        END IF;
    END IF;
    RETURN NEW;
END;
$fn$;
CREATE TRIGGER trg_036_bien_parcela
    BEFORE INSERT OR UPDATE OF id_afectacion,id_parcela,activo ON bien_afectado
    FOR EACH ROW EXECUTE FUNCTION fn_036_validar_bien_parcela();

CREATE OR REPLACE FUNCTION fn_036_sync_asamblea_catalogos()
RETURNS TRIGGER LANGUAGE plpgsql AS $fn$
DECLARE v_tipo TEXT; v_contexto TEXT;
BEGIN
    IF NOT fn_036_opcion_catalogo_valida(NEW.id_tipo_asamblea,'tipo_asamblea')
       OR NOT fn_036_opcion_catalogo_valida(NEW.id_contexto_asamblea,'contexto_asamblea') THEN
        RAISE EXCEPTION 'Tipo o contexto de asamblea inválido';
    END IF;
    SELECT codigo INTO v_tipo FROM catalogo_operativo WHERE id_catalogo_opcion=NEW.id_tipo_asamblea;
    SELECT codigo INTO v_contexto FROM catalogo_operativo WHERE id_catalogo_opcion=NEW.id_contexto_asamblea;
    IF (v_tipo='retiro_fondos' AND v_contexto IS DISTINCT FROM 'retiro_fondos')
       OR (v_tipo='anuencia' AND v_contexto='retiro_fondos') THEN
        RAISE EXCEPTION 'Tipo de asamblea y contexto contradictorios';
    END IF;
    NEW.tipo_asamblea := v_tipo;
    NEW.contexto_proceso := v_contexto;
    RETURN NEW;
END;
$fn$;
CREATE TRIGGER trg_036_asamblea_catalogos
    BEFORE INSERT OR UPDATE OF id_tipo_asamblea,id_contexto_asamblea,tipo_asamblea,contexto_proceso ON asamblea
    FOR EACH ROW EXECUTE FUNCTION fn_036_sync_asamblea_catalogos();

CREATE OR REPLACE FUNCTION fn_036_validar_tramite_ran()
RETURNS TRIGGER LANGUAGE plpgsql AS $fn$
DECLARE v_pn INTEGER; v_nucleo_obj INTEGER; v_nucleo_pn INTEGER;
BEGIN
    IF NEW.id_asamblea IS NOT NULL THEN
        SELECT id_proyecto_nucleo INTO v_pn FROM asamblea WHERE id_asamblea=NEW.id_asamblea AND activo;
    ELSIF NEW.id_convenio IS NOT NULL THEN
        SELECT id_proyecto_nucleo INTO v_pn FROM convenio WHERE id_convenio=NEW.id_convenio AND activo;
    ELSE
        SELECT id_nucleo INTO v_nucleo_obj FROM orv WHERE id_orv=NEW.id_orv AND activo;
        SELECT id_nucleo INTO v_nucleo_pn FROM proyecto_nucleo WHERE id_proyecto_nucleo=NEW.id_proyecto_nucleo AND activo;
        IF v_nucleo_obj IS NULL OR v_nucleo_pn IS NULL OR v_nucleo_obj<>v_nucleo_pn THEN
            RAISE EXCEPTION 'El ORV del trámite RAN debe pertenecer al núcleo del expediente';
        END IF;
        RETURN NEW;
    END IF;
    IF v_pn IS NULL OR v_pn<>NEW.id_proyecto_nucleo THEN
        RAISE EXCEPTION 'El objetivo RAN debe pertenecer al mismo ProyectoNucleo';
    END IF;
    RETURN NEW;
END;
$fn$;
