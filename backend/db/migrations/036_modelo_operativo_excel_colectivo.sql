CREATE TABLE catalogo_operativo (
    id_catalogo_opcion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_catalogo VARCHAR(50) NOT NULL,
    codigo VARCHAR(80) NOT NULL,
    nombre VARCHAR(250) NOT NULL,
    descripcion TEXT,
    orden INTEGER NOT NULL DEFAULT 0,
    fuente VARCHAR(250),
    vigencia_inicio DATE,
    vigencia_fin DATE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    creado_por INTEGER REFERENCES usuario(id_usuario),
    actualizado_en TIMESTAMPTZ,
    actualizado_por INTEGER REFERENCES usuario(id_usuario),
    fecha_baja TIMESTAMPTZ,
    id_usuario_baja INTEGER REFERENCES usuario(id_usuario),
    motivo_baja TEXT,
    observaciones TEXT,
