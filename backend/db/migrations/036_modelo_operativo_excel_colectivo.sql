    CONSTRAINT chk_catalogo_operativo_tipo CHECK (NULLIF(btrim(tipo_catalogo), '') IS NOT NULL),
    CONSTRAINT chk_catalogo_operativo_codigo CHECK (codigo ~ '^[A-Za-z0-9][A-Za-z0-9_-]*$'),
