    v_revision_detalle TEXT;
BEGIN
    SELECT id_catalogo_opcion INTO v_tipo_tierra_nd
    FROM catalogo_operativo WHERE tipo_catalogo='tipo_tierra' AND codigo='no_determinada';
    SELECT id_catalogo_opcion INTO v_tit_nucleo
    FROM catalogo_operativo WHERE tipo_catalogo='tipo_titularidad_unidad' AND codigo='nucleo_agrario';
    SELECT id_catalogo_opcion INTO v_tit_persona
    FROM catalogo_operativo WHERE tipo_catalogo='tipo_titularidad_unidad' AND codigo='persona';
    SELECT id_catalogo_opcion INTO v_tit_copropiedad
    FROM catalogo_operativo WHERE tipo_catalogo='tipo_titularidad_unidad' AND codigo='copropiedad';
    SELECT id_catalogo_opcion INTO v_tit_nd
    FROM catalogo_operativo WHERE tipo_catalogo='tipo_titularidad_unidad' AND codigo='no_determinada';

    FOR r IN
        SELECT b.*, a.id_proyecto_nucleo, a.tipo_afectacion,
               COALESCE(b.id_parcela,a.id_parcela) AS parcela_efectiva,
               pn.id_nucleo
        FROM bien_afectado b
        JOIN afectacion a ON a.id_afectacion=b.id_afectacion
        JOIN proyecto_nucleo pn ON pn.id_proyecto_nucleo=a.id_proyecto_nucleo
        ORDER BY b.id_bien_afectado
    LOOP
        v_ref_norm := fn_037_normalizar_referencia(r.referencia_alfanumerica);
        v_revision := FALSE;
        v_revision_detalle := NULL;

        IF r.tipo_afectacion='colectivo' THEN
            v_titularidad := v_tit_nucleo;
        ELSIF r.parcela_efectiva IS NOT NULL THEN
            SELECT count(*) INTO v_titulares
            FROM parcela_titular
            WHERE id_parcela=r.parcela_efectiva AND activo;
            IF v_titulares=1 THEN
                v_titularidad := v_tit_persona;
            ELSIF v_titulares>1 THEN
                v_titularidad := v_tit_copropiedad;
            ELSE
                v_titularidad := v_tit_nd;
                v_revision := TRUE;
                v_revision_detalle := 'Afectacion individual sin titular activo identificable durante backfill 037.';
            END IF;
        ELSE
            v_titularidad := v_tit_nd;
            v_revision := TRUE;
            v_revision_detalle := 'No fue posible determinar titularidad durante backfill 037.';
        END IF;

        v_unidad := NULL;

        -- Reutilizacion conservadora: misma parcela + mismo tipo de titularidad.
        IF r.parcela_efectiva IS NOT NULL THEN
            SELECT u.id_unidad_agraria, u.id_tipo_gestion, u.id_destino_superficie, u.id_tipo_titularidad
              INTO v_unidad, v_existing_gestion, v_existing_destino, v_existing_tit
            FROM unidad_agraria u
            WHERE u.id_nucleo=r.id_nucleo
              AND u.id_parcela=r.parcela_efectiva
              AND u.id_tipo_titularidad=v_titularidad
              AND u.activo
            ORDER BY u.id_unidad_agraria
            LIMIT 1;
        ELSIF v_ref_norm IS NOT NULL THEN
            SELECT u.id_unidad_agraria, u.id_tipo_gestion, u.id_destino_superficie, u.id_tipo_titularidad
              INTO v_unidad, v_existing_gestion, v_existing_destino, v_existing_tit
            FROM unidad_agraria u
            WHERE u.id_nucleo=r.id_nucleo
              AND u.id_parcela IS NULL
              AND u.referencia_normalizada=v_ref_norm
              AND u.id_tipo_titularidad=v_titularidad
              AND u.activo
            ORDER BY u.id_unidad_agraria
            LIMIT 1;
        END IF;

        IF v_unidad IS NULL THEN
            IF r.parcela_efectiva IS NULL AND v_ref_norm IS NULL THEN
                v_revision := TRUE;
                v_revision_detalle := concat_ws(' ',v_revision_detalle,
                    'Unidad creada sin parcela/referencia estable; revisar posible deduplicacion del bien 036.');
            END IF;

            INSERT INTO unidad_agraria (
                id_nucleo,id_tipo_tierra,id_tipo_gestion,id_destino_superficie,
                id_tipo_titularidad,id_parcela,referencia_alfanumerica,detalle,fuente,
                requiere_revision,motivo_revision,creado_por,observaciones
            ) VALUES (
                r.id_nucleo,v_tipo_tierra_nd,r.id_tipo_gestion,r.id_destino_superficie,
                v_titularidad,r.parcela_efectiva,r.referencia_alfanumerica,r.detalle,
                COALESCE(r.fuente,'backfill_036'),v_revision,v_revision_detalle,
                COALESCE(r.creado_por,NULLIF(current_setting('app.current_user_id',TRUE),'')::INTEGER),
                'Creada por migracion 037 desde bien_afectado '||r.id_bien_afectado
            ) RETURNING id_unidad_agraria INTO v_unidad;
        ELSE
            -- Si el mismo identificador trae clasificaciones contradictorias, no se sobreescribe:
            -- se conserva la primera y se marca revision.
            IF (v_existing_gestion IS DISTINCT FROM r.id_tipo_gestion AND r.id_tipo_gestion IS NOT NULL)
               OR (v_existing_destino IS DISTINCT FROM r.id_destino_superficie AND r.id_destino_superficie IS NOT NULL) THEN
                UPDATE unidad_agraria
                SET requiere_revision=TRUE,
                    motivo_revision=concat_ws(' ',motivo_revision,
                        'Conflicto de tipo_gestion/destino detectado durante backfill 037.'),
                    actualizado_en=now(),
                    actualizado_por=NULLIF(current_setting('app.current_user_id',TRUE),'')::INTEGER
                WHERE id_unidad_agraria=v_unidad;
            END IF;
        END IF;

        UPDATE bien_afectado
        SET id_unidad_agraria=v_unidad,
            actualizado_en=COALESCE(actualizado_en,now()),
            actualizado_por=COALESCE(actualizado_por,NULLIF(current_setting('app.current_user_id',TRUE),'')::INTEGER)
        WHERE id_bien_afectado=r.id_bien_afectado;

        IF NOT EXISTS (
            SELECT 1 FROM afectacion_unidad_agraria au
            WHERE au.id_afectacion=r.id_afectacion
              AND au.id_unidad_agraria=v_unidad
              AND au.activo
        ) THEN
            INSERT INTO afectacion_unidad_agraria (
                id_afectacion,id_unidad_agraria,superficie_preliminar_ha,
                superficie_afectada_ha,superficie_valor_original,
                superficie_formato_origen,fuente,creado_por,observaciones
            ) VALUES (
                r.id_afectacion,v_unidad,r.superficie_preliminar_ha,
                r.superficie_afectada_ha,r.superficie_valor_original,
                r.superficie_formato_origen,COALESCE(r.fuente,'backfill_036'),
                COALESCE(r.creado_por,NULLIF(current_setting('app.current_user_id',TRUE),'')::INTEGER),
                'Backfill desde bien_afectado '||r.id_bien_afectado
            );
        ELSE
            -- No sumar superficies: varias filas legacy pueden ser repeticion del mismo hecho.
            UPDATE afectacion_unidad_agraria
            SET observaciones=concat_ws(E'\n',observaciones,
                    'Bien legacy adicional '||r.id_bien_afectado||' resolvio a la misma unidad; superficie no sumada automaticamente.'),
                actualizado_en=now(),
                actualizado_por=NULLIF(current_setting('app.current_user_id',TRUE),'')::INTEGER
            WHERE id_afectacion=r.id_afectacion
              AND id_unidad_agraria=v_unidad
              AND activo;
        END IF;
    END LOOP;
END;
