    FROM bien_afectado
    GROUP BY id_afectacion
)
UPDATE afectacion a
SET id_tipo_cop_operativo = cop.unico
FROM cop
WHERE cop.id_afectacion=a.id_afectacion AND cop.n=1;

WITH cop AS (
