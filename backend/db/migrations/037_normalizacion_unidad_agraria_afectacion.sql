CREATE OR REPLACE FUNCTION fn_037_validar_pn_tuc()
RETURNS TRIGGER LANGUAGE plpgsql AS $fn$
DECLARE
    v_codigo TEXT;
BEGIN
    IF NOT fn_036_opcion_catalogo_valida(NEW.id_motivo_no_afecta_tuc,'motivo_no_afecta_tuc') THEN
        RAISE EXCEPTION 'Motivo de no afectacion TUC invalido';
    END IF;

    IF NEW.afecta_tuc IS FALSE THEN
        SELECT codigo INTO v_codigo
        FROM catalogo_operativo
        WHERE id_catalogo_opcion=NEW.id_motivo_no_afecta_tuc;
        IF v_codigo='otro' AND NULLIF(btrim(NEW.motivo_no_afecta_tuc_detalle),'') IS NULL THEN
            RAISE EXCEPTION 'El motivo otro requiere detalle';
        END IF;
    END IF;
    RETURN NEW;
END;
$fn$;
CREATE TRIGGER trg_037_pn_tuc
    BEFORE INSERT OR UPDATE OF afecta_tuc,id_motivo_no_afecta_tuc,motivo_no_afecta_tuc_detalle
    ON proyecto_nucleo FOR EACH ROW EXECUTE FUNCTION fn_037_validar_pn_tuc();

