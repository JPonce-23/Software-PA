-- ---------------------------------------------------------------------------
-- 10. Compatibilidad temporal de nuevas escrituras en bien_afectado 036.
--     Mientras el backend migra al API canónico, cada bien legacy recibe/crea
--     una unidad y proyecta su superficie a afectacion_unidad_agraria.
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION fn_037_bien_legacy_preparar_unidad()
RETURNS TRIGGER LANGUAGE plpgsql AS $fn$
DECLARE
    v_nucleo INTEGER;
    v_tipo_tierra BIGINT;
    v_titularidad BIGINT;
    v_tit_persona BIGINT;
    v_tit_cop BIGINT;
    v_tit_nd BIGINT;
    v_tit_nucleo BIGINT;
    v_tipo_afectacion TEXT;
    v_parcela INTEGER;
    v_count INTEGER;
    v_ref TEXT;
BEGIN
    SELECT pn.id_nucleo,a.tipo_afectacion,COALESCE(NEW.id_parcela,a.id_parcela)
      INTO v_nucleo,v_tipo_afectacion,v_parcela
    FROM afectacion a
    JOIN proyecto_nucleo pn ON pn.id_proyecto_nucleo=a.id_proyecto_nucleo
    WHERE a.id_afectacion=NEW.id_afectacion AND a.activo AND pn.activo;
    IF v_nucleo IS NULL THEN
        RAISE EXCEPTION 'El bien legacy requiere una afectacion activa con ProyectoNucleo activo';
    END IF;

    IF NEW.id_unidad_agraria IS NOT NULL THEN
        IF NOT EXISTS (
            SELECT 1 FROM unidad_agraria u
            WHERE u.id_unidad_agraria=NEW.id_unidad_agraria
              AND u.id_nucleo=v_nucleo AND u.activo
        ) THEN
            RAISE EXCEPTION 'La unidad agraria del bien legacy debe pertenecer al mismo nucleo';
        END IF;
        RETURN NEW;
    END IF;

    SELECT id_catalogo_opcion INTO v_tipo_tierra
    FROM catalogo_operativo WHERE tipo_catalogo='tipo_tierra' AND codigo='no_determinada';
    SELECT id_catalogo_opcion INTO v_tit_nucleo
    FROM catalogo_operativo WHERE tipo_catalogo='tipo_titularidad_unidad' AND codigo='nucleo_agrario';
    SELECT id_catalogo_opcion INTO v_tit_persona
    FROM catalogo_operativo WHERE tipo_catalogo='tipo_titularidad_unidad' AND codigo='persona';
    SELECT id_catalogo_opcion INTO v_tit_cop
    FROM catalogo_operativo WHERE tipo_catalogo='tipo_titularidad_unidad' AND codigo='copropiedad';
    SELECT id_catalogo_opcion INTO v_tit_nd
    FROM catalogo_operativo WHERE tipo_catalogo='tipo_titularidad_unidad' AND codigo='no_determinada';

    IF v_tipo_afectacion='colectivo' THEN
        v_titularidad:=v_tit_nucleo;
    ELSIF v_parcela IS NOT NULL THEN
        SELECT count(*) INTO v_count FROM parcela_titular WHERE id_parcela=v_parcela AND activo;
        v_titularidad:=CASE WHEN v_count=1 THEN v_tit_persona WHEN v_count>1 THEN v_tit_cop ELSE v_tit_nd END;
    ELSE
        v_titularidad:=v_tit_nd;
    END IF;

    v_ref:=fn_037_normalizar_referencia(NEW.referencia_alfanumerica);

    IF v_parcela IS NOT NULL THEN
        SELECT id_unidad_agraria INTO NEW.id_unidad_agraria
        FROM unidad_agraria
        WHERE id_nucleo=v_nucleo AND id_parcela=v_parcela
          AND id_tipo_titularidad=v_titularidad AND activo
        ORDER BY id_unidad_agraria LIMIT 1;
    ELSIF v_ref IS NOT NULL THEN
        SELECT id_unidad_agraria INTO NEW.id_unidad_agraria
        FROM unidad_agraria
        WHERE id_nucleo=v_nucleo AND id_parcela IS NULL
          AND referencia_normalizada=v_ref
          AND id_tipo_titularidad=v_titularidad AND activo
        ORDER BY id_unidad_agraria LIMIT 1;
    END IF;

    IF NEW.id_unidad_agraria IS NULL THEN
        INSERT INTO unidad_agraria (
            id_nucleo,id_tipo_tierra,id_tipo_gestion,id_destino_superficie,
            id_tipo_titularidad,id_parcela,referencia_alfanumerica,detalle,fuente,
            requiere_revision,motivo_revision,creado_por,observaciones
        ) VALUES (
            v_nucleo,v_tipo_tierra,NEW.id_tipo_gestion,NEW.id_destino_superficie,
            v_titularidad,v_parcela,NEW.referencia_alfanumerica,NEW.detalle,
            COALESCE(NEW.fuente,'compatibilidad_bien_afectado_036'),
            (v_parcela IS NULL AND v_ref IS NULL),
            CASE WHEN v_parcela IS NULL AND v_ref IS NULL
                 THEN 'Unidad creada por compatibilidad 036 sin identificador estable; revisar.' END,
            COALESCE(NEW.creado_por,NULLIF(current_setting('app.current_user_id',TRUE),'')::INTEGER),
            'Creada automaticamente por compatibilidad temporal de bien_afectado.'
        ) RETURNING id_unidad_agraria INTO NEW.id_unidad_agraria;
    END IF;

    -- Completa valores faltantes, pero nunca sobreescribe silenciosamente una
    -- clasificacion canónica distinta: en conflicto marca revision.
    UPDATE unidad_agraria u
    SET id_tipo_gestion=COALESCE(u.id_tipo_gestion,NEW.id_tipo_gestion),
        id_destino_superficie=COALESCE(u.id_destino_superficie,NEW.id_destino_superficie),
        requiere_revision=u.requiere_revision OR
            (u.id_tipo_gestion IS NOT NULL AND NEW.id_tipo_gestion IS NOT NULL AND u.id_tipo_gestion<>NEW.id_tipo_gestion) OR
            (u.id_destino_superficie IS NOT NULL AND NEW.id_destino_superficie IS NOT NULL AND u.id_destino_superficie<>NEW.id_destino_superficie),
        motivo_revision=CASE
            WHEN (u.id_tipo_gestion IS NOT NULL AND NEW.id_tipo_gestion IS NOT NULL AND u.id_tipo_gestion<>NEW.id_tipo_gestion)
              OR (u.id_destino_superficie IS NOT NULL AND NEW.id_destino_superficie IS NOT NULL AND u.id_destino_superficie<>NEW.id_destino_superficie)
            THEN concat_ws(' ',u.motivo_revision,'Conflicto detectado desde escritura legacy bien_afectado.')
            ELSE u.motivo_revision END,
        actualizado_en=now(),
        actualizado_por=COALESCE(NEW.actualizado_por,NEW.creado_por,NULLIF(current_setting('app.current_user_id',TRUE),'')::INTEGER)
    WHERE u.id_unidad_agraria=NEW.id_unidad_agraria;

    -- Si la unidad individual se resolvio a persona/copropiedad, reutiliza
    -- los titulares parcelarios existentes; no crea personas duplicadas.
    IF v_tipo_afectacion='individual' AND v_parcela IS NOT NULL THEN
        INSERT INTO unidad_agraria_titular (
            id_unidad_agraria,id_parcela_titular,porcentaje_participacion,es_principal,
            creado_por,observaciones
        )
        SELECT NEW.id_unidad_agraria,pt.id_parcela_titular,pt.porcentaje_participacion,
               row_number() OVER (ORDER BY pt.id_parcela_titular)=1,
               COALESCE(NEW.creado_por,NULLIF(current_setting('app.current_user_id',TRUE),'')::INTEGER),
               'Sincronizacion temporal desde ParcelaTitular por compatibilidad 036.'
        FROM parcela_titular pt
        WHERE pt.id_parcela=v_parcela AND pt.activo
          AND NOT EXISTS (
              SELECT 1 FROM unidad_agraria_titular ut
              WHERE ut.id_unidad_agraria=NEW.id_unidad_agraria
                AND ut.id_parcela_titular=pt.id_parcela_titular
                AND ut.activo
          );
    END IF;

    RETURN NEW;
END;
$fn$;

CREATE TRIGGER trg_037_bien_legacy_preparar_unidad
    BEFORE INSERT OR UPDATE OF id_afectacion,id_tipo_gestion,id_destino_superficie,
        id_parcela,referencia_alfanumerica,id_unidad_agraria
    ON bien_afectado
    FOR EACH ROW EXECUTE FUNCTION fn_037_bien_legacy_preparar_unidad();

CREATE OR REPLACE FUNCTION fn_037_bien_legacy_proyectar()
RETURNS TRIGGER LANGUAGE plpgsql AS $fn$
DECLARE
    v_count INTEGER;
    v_actual BIGINT;
BEGIN
    IF NEW.activo AND NEW.id_unidad_agraria IS NOT NULL THEN
        SELECT count(*), min(id_afectacion_unidad)
          INTO v_count,v_actual
        FROM afectacion_unidad_agraria
        WHERE id_afectacion=NEW.id_afectacion
          AND id_unidad_agraria=NEW.id_unidad_agraria
          AND activo;

        IF v_count=0 THEN
            INSERT INTO afectacion_unidad_agraria (
                id_afectacion,id_unidad_agraria,superficie_preliminar_ha,
                superficie_afectada_ha,superficie_valor_original,
                superficie_formato_origen,fuente,creado_por,observaciones
            ) VALUES (
                NEW.id_afectacion,NEW.id_unidad_agraria,NEW.superficie_preliminar_ha,
                NEW.superficie_afectada_ha,NEW.superficie_valor_original,
                NEW.superficie_formato_origen,COALESCE(NEW.fuente,'compatibilidad_bien_afectado_036'),
                COALESCE(NEW.creado_por,NULLIF(current_setting('app.current_user_id',TRUE),'')::INTEGER),
                'Proyeccion automatica desde bien_afectado legacy.'
            );
        ELSE
            UPDATE afectacion_unidad_agraria
            SET superficie_preliminar_ha=NEW.superficie_preliminar_ha,
                superficie_afectada_ha=NEW.superficie_afectada_ha,
                superficie_valor_original=NEW.superficie_valor_original,
                superficie_formato_origen=NEW.superficie_formato_origen,
                actualizado_en=now(),
                actualizado_por=COALESCE(NEW.actualizado_por,NULLIF(current_setting('app.current_user_id',TRUE),'')::INTEGER)
            WHERE id_afectacion_unidad=v_actual;
        END IF;

        IF NEW.id_tipo_cop_operativo IS NOT NULL THEN
            UPDATE afectacion
            SET id_tipo_cop_operativo=CASE
                    WHEN id_tipo_cop_operativo IS NULL THEN NEW.id_tipo_cop_operativo
                    ELSE id_tipo_cop_operativo END,
                tipo_cop_revision_pendiente=CASE
                    WHEN id_tipo_cop_operativo IS NOT NULL
                     AND id_tipo_cop_operativo<>NEW.id_tipo_cop_operativo THEN TRUE
                    ELSE tipo_cop_revision_pendiente END,
                tipo_cop_revision_detalle=CASE
                    WHEN id_tipo_cop_operativo IS NOT NULL
                     AND id_tipo_cop_operativo<>NEW.id_tipo_cop_operativo
                    THEN 'Conflicto generado por escritura legacy bien_afectado: mas de un TIPO COP para la misma Afectacion.'
                    ELSE tipo_cop_revision_detalle END,
                actualizado_en=now(),
                actualizado_por=COALESCE(NEW.actualizado_por,NULLIF(current_setting('app.current_user_id',TRUE),'')::INTEGER)
            WHERE id_afectacion=NEW.id_afectacion;
        END IF;
    END IF;
    RETURN NEW;
END;
