DECLARE
    v_environment TEXT := lower(current_setting('app.environment', TRUE));
    v_confirm TEXT := current_setting('app.allow_destructive_test_reset', TRUE);
    v_backup TEXT := current_setting('app.backup_verified', TRUE);
BEGIN
    IF v_environment IS NULL
       OR v_environment NOT IN ('development', 'test')
       OR current_database() !~* '(test|prueba|dev|local)'
       OR v_confirm IS DISTINCT FROM '1'
       OR v_backup IS DISTINCT FROM '1' THEN
        RAISE EXCEPTION '032 bloqueada: entorno, confirmación o respaldo no válidos';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM schema_migrations WHERE version = '031') THEN
        RAISE EXCEPTION '032 requiere la migración 031';
    END IF;
    IF EXISTS (SELECT 1 FROM schema_migrations WHERE version = '032') THEN
        RAISE EXCEPTION 'La migración 032 ya fue aplicada';
    END IF;
END;
