CREATE TABLE trazo_proyecto (
    id_trazo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proyecto INTEGER NOT NULL REFERENCES proyecto(id_proyecto),
    version INTEGER NOT NULL,
    geometria_linea geometry(MULTILINESTRING, 4326) NOT NULL,
    fuente VARCHAR(250) NOT NULL,
    fecha_fuente DATE,
    fecha_vigencia_inicio DATE NOT NULL,
    fecha_vigencia_fin DATE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    creado_por INTEGER REFERENCES usuario(id_usuario),
    actualizado_en TIMESTAMPTZ,
    actualizado_por INTEGER REFERENCES usuario(id_usuario),
    fecha_baja TIMESTAMPTZ,
    id_usuario_baja INTEGER REFERENCES usuario(id_usuario),
    motivo_baja TEXT,
    observaciones TEXT,
    CONSTRAINT uq_trazo_proyecto_version UNIQUE (id_proyecto, version),
    CONSTRAINT chk_trazo_version CHECK (version > 0),
    CONSTRAINT chk_trazo_fuente CHECK (NULLIF(btrim(fuente), '') IS NOT NULL),
    CONSTRAINT chk_trazo_vigencia CHECK (fecha_vigencia_fin IS NULL OR fecha_vigencia_fin >= fecha_vigencia_inicio),
    CONSTRAINT chk_trazo_geometria CHECK (
        NOT ST_IsEmpty(geometria_linea)
        AND ST_IsValid(geometria_linea)
        AND ST_SRID(geometria_linea) = 4326
        AND GeometryType(geometria_linea) = 'MULTILINESTRING'
    ),
    CONSTRAINT chk_trazo_baja CHECK (
        (activo AND fecha_baja IS NULL AND id_usuario_baja IS NULL AND motivo_baja IS NULL)
        OR (NOT activo AND fecha_baja IS NOT NULL AND id_usuario_baja IS NOT NULL AND NULLIF(btrim(motivo_baja), '') IS NOT NULL)
    )
);
CREATE UNIQUE INDEX uq_trazo_proyecto_activo ON trazo_proyecto (id_proyecto) WHERE activo;
CREATE INDEX idx_trazo_proyecto_geom ON trazo_proyecto USING gist (geometria_linea);

