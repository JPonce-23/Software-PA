CREATE FUNCTION fn_gis_validar_candidato() RETURNS trigger LANGUAGE plpgsql AS $$
 DECLARE v_proyecto integer; v_objetivo text; v_version text;
 BEGIN
 SELECT id_proyecto,tipo_objetivo,version_pipeline INTO v_proyecto,v_objetivo,v_version
 FROM importacion_archivo WHERE id_importacion=NEW.id_importacion AND activo;
 IF v_proyecto IS NULL OR v_version='legacy-v1' OR NOT EXISTS(
 SELECT 1 FROM proyecto_nucleo pn JOIN nucleo_agrario n USING(id_nucleo) JOIN proyecto pr USING(id_proyecto)
 WHERE pn.id_proyecto_nucleo=NEW.id_proyecto_nucleo AND pn.id_proyecto=v_proyecto AND pn.activo AND n.activo AND pr.activo)
 THEN RAISE EXCEPTION 'Candidato fuera del universo administrativo del proyecto'; END IF;
 IF v_objetivo IN('parcela','parcela_gpkg') THEN
  IF NEW.id_parcela IS NULL OR NOT EXISTS(SELECT 1 FROM vw_gis_parcela_proyecto
   WHERE id_proyecto_nucleo=NEW.id_proyecto_nucleo AND id_parcela=NEW.id_parcela AND id_proyecto=v_proyecto)
  THEN RAISE EXCEPTION 'Parcela sin vinculo administrativo activo con el proyecto'; END IF;
 ELSIF v_objetivo IN('nucleo_agrario','nucleo_agrario_gpkg') THEN
  IF NEW.id_parcela IS NOT NULL THEN RAISE EXCEPTION 'Destino no corresponde a nucleo'; END IF;
 ELSE RAISE EXCEPTION 'Objetivo no conciliable'; END IF;
 IF NEW.estado IN('seleccionado','confirmado') AND NOT EXISTS(SELECT 1 FROM usuario
 WHERE id_usuario=NULLIF(current_setting('app.current_user_id',true),'')::integer AND activo AND rol IN('admin','geografo'))
 THEN RAISE EXCEPTION 'Decision GIS requiere admin o geografo'; END IF;
 IF TG_OP='UPDATE' AND OLD.estado='confirmado' AND to_jsonb(NEW) IS DISTINCT FROM to_jsonb(OLD)
 THEN RAISE EXCEPTION 'Candidato confirmado inmutable'; END IF;
 RETURN NEW;
 END $$;
CREATE TRIGGER trg_gis_candidato_ambito BEFORE INSERT OR UPDATE ON importacion_feature_candidato
 FOR EACH ROW EXECUTE FUNCTION fn_gis_validar_candidato();

CREATE FUNCTION fn_gis_validar_geometria_contexto() RETURNS trigger LANGUAGE plpgsql AS $$
 DECLARE v_feature importacion_feature%ROWTYPE; v_import importacion_archivo%ROWTYPE;
 BEGIN
 SELECT * INTO v_feature FROM importacion_feature WHERE id_importacion_feature=NEW.id_importacion_feature;
 SELECT * INTO v_import FROM importacion_archivo WHERE id_importacion=v_feature.id_importacion;
 IF v_feature.estado_conciliacion<>'confirmado' OR NOT EXISTS(
 SELECT 1 FROM importacion_feature_candidato c JOIN proyecto_nucleo pn USING(id_proyecto_nucleo)
 WHERE c.id_importacion_feature=NEW.id_importacion_feature AND c.estado='confirmado'
 AND c.id_proyecto_nucleo=NEW.id_proyecto_nucleo AND pn.id_proyecto=v_import.id_proyecto
 AND ((TG_TABLE_NAME='proyecto_nucleo_geometria' AND c.id_parcela IS NULL)
 OR (TG_TABLE_NAME='proyecto_parcela_geometria' AND c.id_parcela=(to_jsonb(NEW)->>'id_parcela')::integer)))
 THEN RAISE EXCEPTION 'Geometria sin destino confirmado del mismo proyecto'; END IF;
 IF NEW.srid_trabajo<>v_import.srid_trabajo OR NEW.geometria_poligono IS DISTINCT FROM v_feature.geometria_normalizada
 OR NEW.geometria_trabajo IS DISTINCT FROM v_feature.geometria_trabajo
 THEN RAISE EXCEPTION 'Geometria o CRS distintos del staging confirmado'; END IF;
 RETURN NEW;
 END $$;
CREATE TRIGGER trg_nucleo_geometria_contexto BEFORE INSERT OR UPDATE ON proyecto_nucleo_geometria
 FOR EACH ROW EXECUTE FUNCTION fn_gis_validar_geometria_contexto();
CREATE TRIGGER trg_parcela_geometria_contexto BEFORE INSERT OR UPDATE ON proyecto_parcela_geometria
 FOR EACH ROW EXECUTE FUNCTION fn_gis_validar_geometria_contexto();

-- Guardas de CRS: la configuración no puede cambiar mientras existan geometrías confirmadas.
CREATE FUNCTION fn_gis_configuracion_coherente() RETURNS trigger LANGUAGE plpgsql AS $$
 BEGIN
 IF ((TG_OP='INSERT' AND NEW.srid_trabajo<>4326) OR (TG_OP='UPDATE' AND (NEW.srid_trabajo<>OLD.srid_trabajo OR NOT NEW.activo))) AND EXISTS(
 SELECT 1 FROM importacion_archivo WHERE id_proyecto=NEW.id_proyecto AND importados>0 AND version_pipeline<>'legacy-v1')
 THEN RAISE EXCEPTION 'CRS en uso; requiere reproyeccion explicita de las geometrías del proyecto'; END IF;
 RETURN NEW;
 END $$;
CREATE TRIGGER trg_gis_configuracion_coherente BEFORE INSERT OR UPDATE ON proyecto_configuracion_gis
 FOR EACH ROW EXECUTE FUNCTION fn_gis_configuracion_coherente();

