 BEGIN
 IF OLD.estado='confirmado' AND to_jsonb(NEW) IS DISTINCT FROM to_jsonb(OLD) THEN
  RAISE EXCEPTION 'Feature GIS confirmada inmutable; utilizar nueva importacion';
 END IF;
 RETURN NEW;
 END $$;
CREATE TRIGGER trg_gis_feature_confirmada_inmutable BEFORE UPDATE ON importacion_feature
 FOR EACH ROW EXECUTE FUNCTION fn_gis_feature_confirmada_inmutable();
