-- Únicamente relaciones administrativas preexistentes acreditan parcelas del proyecto.
CREATE VIEW vw_gis_parcela_proyecto AS
 SELECT DISTINCT pn.id_proyecto,pn.id_proyecto_nucleo,p.id_parcela,p.id_nucleo
 FROM proyecto_nucleo pn JOIN proyecto pr USING(id_proyecto)
 JOIN nucleo_agrario n USING(id_nucleo)
 JOIN afectacion a USING(id_proyecto_nucleo)
 JOIN afectacion_unidad_agraria au USING(id_afectacion)
 JOIN unidad_agraria u USING(id_unidad_agraria)
 JOIN parcela p ON p.id_parcela=u.id_parcela AND p.id_nucleo=pn.id_nucleo AND u.id_nucleo=pn.id_nucleo
 WHERE pn.activo AND pr.activo AND n.activo AND a.activo AND au.activo AND u.activo AND p.activo;
COMMENT ON VIEW vw_gis_parcela_proyecto IS
 'Universo GIS de parcelas: sólo vínculos administrativos activos por afectación; ST_Intersects no interviene.';

