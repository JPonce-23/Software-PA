CREATE TABLE catalogo_tipo_documento (
    id_tipo_documento bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(80) NOT NULL,
    nombre varchar(250) NOT NULL,
    descripcion text,
    orden integer NOT NULL DEFAULT 0,
    activo boolean NOT NULL DEFAULT true,
    creado_en timestamptz NOT NULL DEFAULT now(),
    creado_por integer REFERENCES usuario(id_usuario),
    actualizado_en timestamptz,
    actualizado_por integer REFERENCES usuario(id_usuario),
    fecha_baja timestamptz,
    id_usuario_baja integer REFERENCES usuario(id_usuario),
    motivo_baja text,
    observaciones text,
    CONSTRAINT uq_catalogo_tipo_documento_codigo UNIQUE (codigo),
    CONSTRAINT chk_catalogo_tipo_documento_codigo CHECK (codigo ~ '^[A-Z][A-Z0-9_]*$'),
    CONSTRAINT chk_catalogo_tipo_documento_nombre CHECK (NULLIF(btrim(nombre), '') IS NOT NULL),
    CONSTRAINT chk_catalogo_tipo_documento_orden CHECK (orden >= 0),
    CONSTRAINT chk_catalogo_tipo_documento_baja CHECK (
        (activo AND fecha_baja IS NULL AND id_usuario_baja IS NULL AND motivo_baja IS NULL)
        OR (NOT activo AND fecha_baja IS NOT NULL AND id_usuario_baja IS NOT NULL
            AND NULLIF(btrim(motivo_baja), '') IS NOT NULL)
    )
);

