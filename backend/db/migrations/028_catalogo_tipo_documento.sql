CREATE FUNCTION fn_catalogo_tipo_documento_codigo_inmutable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.codigo IS DISTINCT FROM OLD.codigo THEN
        RAISE EXCEPTION 'El código documental es inmutable'
            USING ERRCODE = '23514', CONSTRAINT = 'catalogo_tipo_documento_codigo_inmutable';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_catalogo_tipo_documento_codigo_inmutable
BEFORE UPDATE OF codigo ON catalogo_tipo_documento
FOR EACH ROW EXECUTE FUNCTION fn_catalogo_tipo_documento_codigo_inmutable();
