CREATE FUNCTION fn_validar_clasificacion_documental() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_catalog AS $$
DECLARE
    v_codigo text;
    v_activo boolean;
    v_seleccion boolean;
BEGIN
    v_seleccion := TG_OP = 'INSERT';
    IF TG_OP = 'UPDATE' THEN
        v_seleccion := NEW.id_tipo_documento IS DISTINCT FROM OLD.id_tipo_documento;
        IF OLD.id_tipo_documento IS NOT NULL AND NEW.id_tipo_documento IS NULL THEN
            RAISE EXCEPTION 'No se permite eliminar una clasificación documental'
                USING ERRCODE = '23514', CONSTRAINT = 'documento_clasificacion_irrevocable';
        END IF;
        IF (OLD.id_tipo_documento IS NOT NULL OR NEW.id_tipo_documento IS NOT NULL)
           AND NEW.tipo_documento IS DISTINCT FROM OLD.tipo_documento THEN
            RAISE EXCEPTION 'El texto legado de un documento clasificado se conserva'
                USING ERRCODE = '23514', CONSTRAINT = 'documento_tipo_legado_protegido';
        END IF;
    END IF;
    IF NEW.id_tipo_documento IS NULL THEN RETURN NEW; END IF;

    -- FOR SHARE bloquea también UPDATE de activo, no sólo cambios de clave.
    SELECT codigo, activo INTO v_codigo, v_activo
    FROM catalogo_tipo_documento WHERE id_tipo_documento = NEW.id_tipo_documento
    FOR SHARE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Tipo documental inexistente'
            USING ERRCODE = '23503', CONSTRAINT = 'fk_documento_tipo_documento';
    END IF;
    IF v_seleccion AND NOT v_activo THEN
        RAISE EXCEPTION 'No se permite seleccionar un tipo documental inactivo'
            USING ERRCODE = '23514', CONSTRAINT = 'documento_tipo_catalogo_activo';
    END IF;
    IF v_codigo = 'OTRO' AND NULLIF(btrim(NEW.descripcion), '') IS NULL THEN
        RAISE EXCEPTION 'OTRO requiere descripción no vacía'
            USING ERRCODE = '23514', CONSTRAINT = 'documento_otro_descripcion';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_validar_clasificacion_documental
BEFORE INSERT OR UPDATE OF id_tipo_documento, tipo_documento, descripcion ON documento
FOR EACH ROW EXECUTE FUNCTION fn_validar_clasificacion_documental();

