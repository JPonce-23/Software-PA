CREATE OR REPLACE VIEW vw_seguimiento_estado_actual AS
WITH transicion AS (
  SELECT se.*, co.codigo AS tipo_evento_codigo, mo.codigo AS motivo_codigo,
         row_number() OVER (
             PARTITION BY se.id_proyecto_nucleo, coalesce(se.entidad_tipo,'proyecto_nucleo'),
                          coalesce(se.entidad_id,se.id_proyecto_nucleo)
             ORDER BY se.fecha_evento DESC NULLS LAST, se.id_seguimiento_evento DESC
         ) AS rn
  FROM seguimiento_evento se
  JOIN catalogo_operativo co ON co.id_catalogo_opcion=se.id_tipo_evento
  LEFT JOIN catalogo_operativo mo ON mo.id_catalogo_opcion=se.id_motivo
  WHERE se.activo AND co.codigo IN ('inicio','suspension','reapertura','cierre')
)
SELECT id_proyecto_nucleo, entidad_tipo, entidad_id,
       CASE tipo_evento_codigo WHEN 'suspension' THEN 'suspendido' WHEN 'cierre' THEN 'cerrado' ELSE 'activo' END AS estado_actual,
       tipo_evento_codigo AS tipo_ultimo_evento, motivo_codigo AS motivo_actual,
       fecha_evento AS fecha_ultimo_evento, detalle, ambito
FROM transicion WHERE rn=1;
