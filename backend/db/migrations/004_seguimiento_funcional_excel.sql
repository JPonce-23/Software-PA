CREATE OR REPLACE FUNCTION fn_validar_seguimiento_evento() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_tipo text; v_motivo text;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW.id_proyecto_nucleo <> OLD.id_proyecto_nucleo THEN
            RAISE EXCEPTION 'No se permite cambiar el ProyectoNucleo de un evento de seguimiento';
        END IF;
        IF NEW.ambito <> OLD.ambito THEN
            RAISE EXCEPTION 'No se permite cambiar el ámbito de un evento de seguimiento';
        END IF;
        IF NEW.id_tipo_evento <> OLD.id_tipo_evento THEN
            RAISE EXCEPTION 'No se permite reescribir el tipo de evento; la transición debe registrarse mediante un nuevo evento';
        END IF;
        IF NEW.id_motivo IS DISTINCT FROM OLD.id_motivo THEN
            RAISE EXCEPTION 'No se permite cambiar el motivo de un evento de seguimiento';
        END IF;
        IF (NEW.entidad_tipo IS DISTINCT FROM OLD.entidad_tipo) OR (NEW.entidad_id IS DISTINCT FROM OLD.entidad_id) THEN
            RAISE EXCEPTION 'No se permite cambiar el objetivo de un evento de seguimiento';
        END IF;
    END IF;

    IF NOT fn_opcion_catalogo_valida(NEW.id_tipo_evento,'tipo_evento_seguimiento') THEN
        RAISE EXCEPTION 'Tipo de evento de seguimiento inválido';
    END IF;
    IF NEW.id_motivo IS NOT NULL AND NOT fn_opcion_catalogo_valida(NEW.id_motivo,'motivo_seguimiento') THEN
        RAISE EXCEPTION 'Motivo de seguimiento inválido';
    END IF;
    IF NEW.entidad_tipo IS NOT NULL
       AND NOT fn_objetivo_seguimiento_en_pn(NEW.entidad_tipo,NEW.entidad_id,NEW.id_proyecto_nucleo) THEN
        RAISE EXCEPTION 'El objetivo de seguimiento no existe, está inactivo o no pertenece al ProyectoNucleo';
    END IF;
    SELECT codigo INTO v_tipo FROM catalogo_operativo WHERE id_catalogo_opcion=NEW.id_tipo_evento;
    SELECT codigo INTO v_motivo FROM catalogo_operativo WHERE id_catalogo_opcion=NEW.id_motivo;
    IF v_tipo='suspension' AND NEW.id_motivo IS NULL THEN
        RAISE EXCEPTION 'La suspensión requiere motivo';
    END IF;
    IF v_tipo='reapertura' AND NULLIF(btrim(NEW.detalle),'') IS NULL THEN
        RAISE EXCEPTION 'La reapertura requiere detalle';
    END IF;
    IF v_tipo IN ('cierre','cambio_alcance') AND (NEW.id_motivo IS NULL OR NULLIF(btrim(NEW.detalle),'') IS NULL) THEN
        RAISE EXCEPTION '% requiere motivo y detalle', v_tipo;
    END IF;
    IF v_motivo='otro' AND NULLIF(btrim(NEW.detalle),'') IS NULL THEN
        RAISE EXCEPTION 'El motivo otro requiere detalle';
    END IF;
    IF v_tipo='continuacion_asamblea' AND NEW.entidad_tipo NOT IN ('asamblea','asamblea_convocatoria') THEN
        RAISE EXCEPTION 'La continuación de asamblea requiere objetivo asamblea o convocatoria';
    END IF;
    IF v_motivo='dominio_pleno' AND (NEW.ambito <> 'individual' OR NEW.entidad_tipo NOT IN ('parcela','afectacion','unidad_agraria')) THEN
        RAISE EXCEPTION 'Dominio pleno sólo admite ámbito individual y objetivo parcela, afectación o unidad agraria';
    END IF;
    IF v_motivo IN ('conflicto_titularidad','juicio_agrario') AND (NEW.ambito <> 'individual' OR NEW.entidad_tipo NOT IN ('parcela','parcela_titular','afectacion','unidad_agraria')) THEN
        RAISE EXCEPTION 'Conflicto de titularidad o juicio agrario sólo admite objetivo individual compatible';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_validar_seguimiento_evento ON seguimiento_evento;
