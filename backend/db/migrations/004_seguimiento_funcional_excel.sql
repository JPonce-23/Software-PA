CREATE TABLE IF NOT EXISTS seguimiento_evento (
    id_seguimiento_evento bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proyecto_nucleo integer NOT NULL REFERENCES proyecto_nucleo(id_proyecto_nucleo),
    entidad_tipo varchar(50),
    entidad_id bigint,
    ambito varchar(20) NOT NULL,
    id_tipo_evento bigint NOT NULL REFERENCES catalogo_operativo(id_catalogo_opcion),
    id_motivo bigint REFERENCES catalogo_operativo(id_catalogo_opcion),
    fecha_evento date,
    detalle text,
    id_documento integer REFERENCES documento(id_documento),
    fuente varchar(250),
    activo boolean NOT NULL DEFAULT true,
    creado_en timestamptz NOT NULL DEFAULT now(),
    creado_por integer REFERENCES usuario(id_usuario),
    actualizado_en timestamptz,
    actualizado_por integer REFERENCES usuario(id_usuario),
    fecha_baja timestamptz,
    id_usuario_baja integer REFERENCES usuario(id_usuario),
    motivo_baja text,
    observaciones text,
    CONSTRAINT chk_seguimiento_evento_ambito CHECK (ambito IN ('general','colectivo','individual')),
    CONSTRAINT chk_seguimiento_evento_objetivo CHECK (
        (entidad_tipo IS NULL AND entidad_id IS NULL) OR
        (entidad_tipo IN ('proyecto_nucleo','afectacion','parcela','parcela_titular',
                          'unidad_agraria','asamblea','asamblea_convocatoria','convenio',
                          'tramite_ran','tramite_ran_evento','tramite_fifonafe',
                          'tramite_fifonafe_evento','orv','padron_historial','indemnizacion')
         AND entidad_id IS NOT NULL)
    ),
    CONSTRAINT chk_seguimiento_evento_baja CHECK (
        (activo AND fecha_baja IS NULL AND id_usuario_baja IS NULL AND motivo_baja IS NULL) OR
        (NOT activo AND fecha_baja IS NOT NULL AND id_usuario_baja IS NOT NULL
         AND NULLIF(btrim(motivo_baja),'') IS NOT NULL)
    )
);
CREATE INDEX IF NOT EXISTS ix_seguimiento_evento_pn_fecha
    ON seguimiento_evento(id_proyecto_nucleo, fecha_evento DESC, id_seguimiento_evento DESC)
    WHERE activo;
CREATE INDEX IF NOT EXISTS ix_seguimiento_evento_objetivo
    ON seguimiento_evento(entidad_tipo, entidad_id) WHERE activo;

