CREATE FUNCTION fn_gis_entrega_contexto() RETURNS trigger LANGUAGE plpgsql AS $$
 DECLARE anterior importacion_archivo%ROWTYPE;
 BEGIN
 IF TG_OP='UPDATE' AND (NEW.alcance_entrega<>OLD.alcance_entrega OR
  NEW.id_importacion_anterior IS DISTINCT FROM OLD.id_importacion_anterior)
 THEN RAISE EXCEPTION 'Alcance y procedencia de entrega inmutables'; END IF;
 IF NEW.id_importacion_anterior IS NOT NULL THEN
  SELECT * INTO anterior FROM importacion_archivo WHERE id_importacion=NEW.id_importacion_anterior;
  IF anterior.id_proyecto<>NEW.id_proyecto OR anterior.id_importacion>=NEW.id_importacion OR NOT (
   anterior.tipo_objetivo=NEW.tipo_objetivo OR
   (anterior.tipo_objetivo IN('nucleo_agrario','nucleo_agrario_gpkg') AND NEW.tipo_objetivo IN('nucleo_agrario','nucleo_agrario_gpkg')) OR
   (anterior.tipo_objetivo IN('parcela','parcela_gpkg') AND NEW.tipo_objetivo IN('parcela','parcela_gpkg')))
  THEN RAISE EXCEPTION 'Entrega anterior no comparable del mismo proyecto/objetivo'; END IF;
 END IF;
 RETURN NEW;
END $$;
