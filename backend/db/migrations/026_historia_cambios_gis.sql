CREATE FUNCTION fn_gis_revision_contexto() RETURNS trigger LANGUAGE plpgsql AS $$
 DECLARE v_pn integer; v_parcela integer; v_proyecto integer; v_id bigint; v_tabla text;
 BEGIN
 IF NOT EXISTS(SELECT 1 FROM importacion_archivo WHERE id_importacion=NEW.id_importacion_nueva AND id_proyecto=NEW.id_proyecto)
 OR (NEW.id_importacion_anterior IS NOT NULL AND NOT EXISTS(SELECT 1 FROM importacion_archivo
 WHERE id_importacion=NEW.id_importacion_anterior AND id_proyecto=NEW.id_proyecto))
 THEN RAISE EXCEPTION 'Revisión con importaciones de otro proyecto'; END IF;
 IF NEW.id_proyecto_nucleo IS NOT NULL AND NOT EXISTS(SELECT 1 FROM proyecto_nucleo
 WHERE id_proyecto_nucleo=NEW.id_proyecto_nucleo AND id_proyecto=NEW.id_proyecto)
 THEN RAISE EXCEPTION 'Revisión con destino de otro proyecto'; END IF;
 IF NEW.id_feature_nueva IS NOT NULL AND NOT EXISTS(SELECT 1 FROM importacion_feature
 WHERE id_importacion_feature=NEW.id_feature_nueva AND id_importacion=NEW.id_importacion_nueva)
 THEN RAISE EXCEPTION 'Feature de otra entrega'; END IF;
 FOR v_tabla,v_id IN SELECT * FROM (VALUES
 ('proyecto_nucleo_geometria',NEW.id_nucleo_geometria_anterior),('proyecto_nucleo_geometria',NEW.id_nucleo_geometria_nueva),
 ('proyecto_parcela_geometria',NEW.id_parcela_geometria_anterior),('proyecto_parcela_geometria',NEW.id_parcela_geometria_nueva)) x LOOP
  IF v_id IS NOT NULL THEN
   EXECUTE format('SELECT id_proyecto_nucleo,(to_jsonb(g)->>''id_parcela'')::integer FROM %I g WHERE id_geometria=$1',v_tabla)
    INTO v_pn,v_parcela USING v_id;
   IF v_pn IS DISTINCT FROM NEW.id_proyecto_nucleo OR v_parcela IS DISTINCT FROM NEW.id_parcela
   THEN RAISE EXCEPTION 'Versión geométrica de otra entidad'; END IF;
  END IF;
 END LOOP;
 IF EXISTS(SELECT 1 FROM derecho_via_proyecto WHERE id_derecho_via IN(NEW.id_ddv_anterior,NEW.id_ddv_nueva)
 AND id_proyecto<>NEW.id_proyecto) THEN RAISE EXCEPTION 'DDV de otro proyecto'; END IF;
 IF NEW.id_parcela IS NOT NULL AND NOT EXISTS(SELECT 1 FROM parcela p JOIN proyecto_nucleo pn USING(id_nucleo)
  WHERE p.id_parcela=NEW.id_parcela AND pn.id_proyecto_nucleo=NEW.id_proyecto_nucleo)
 THEN RAISE EXCEPTION 'Parcela de otro núcleo'; END IF;
 IF NEW.tipo_cambio='geometria_modificada' AND NEW.objetivo IN('nucleo','parcela') THEN
  v_tabla:=CASE WHEN NEW.objetivo='nucleo' THEN 'proyecto_nucleo_geometria' ELSE 'proyecto_parcela_geometria' END;
  EXECUTE format('SELECT f.id_importacion FROM %I g JOIN importacion_feature f USING(id_importacion_feature) WHERE g.id_geometria=$1',v_tabla)
   INTO v_id USING COALESCE(NEW.id_nucleo_geometria_anterior,NEW.id_parcela_geometria_anterior);
  IF v_id IS DISTINCT FROM NEW.id_importacion_anterior THEN RAISE EXCEPTION 'Importación anterior distinta de la versión'; END IF;
  EXECUTE format('SELECT f.id_importacion FROM %I g JOIN importacion_feature f USING(id_importacion_feature) WHERE g.id_geometria=$1',v_tabla)
   INTO v_id USING COALESCE(NEW.id_nucleo_geometria_nueva,NEW.id_parcela_geometria_nueva);
  IF v_id<>NEW.id_importacion_nueva THEN RAISE EXCEPTION 'Importación nueva distinta de la versión'; END IF;
 END IF;
 IF NEW.tipo_cambio='desaparece_en_nueva_version' AND NOT EXISTS(
  SELECT 1 FROM importacion_archivo a JOIN importacion_archivo b ON b.id_importacion=NEW.id_importacion_nueva
  WHERE a.id_importacion=NEW.id_importacion_anterior AND a.alcance_entrega='completa' AND b.alcance_entrega='completa'
  AND a.estado='completo' AND b.estado='completo' AND a.id_proyecto=b.id_proyecto AND a.srid_trabajo=b.srid_trabajo)
 THEN RAISE EXCEPTION 'Desaparición requiere entregas completas finalizadas'; END IF;
 RETURN NEW;
END $$;
