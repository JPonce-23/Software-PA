CREATE FUNCTION fn_gis_ciclo_historia() RETURNS trigger LANGUAGE plpgsql AS $$
 BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Ciclo GIS histórico no eliminable'; END IF;
 IF TG_OP='UPDATE' AND (OLD.estado='finalizado' OR
  (to_jsonb(NEW)-ARRAY['estado','fecha_fin','resumen']) IS DISTINCT FROM
  (to_jsonb(OLD)-ARRAY['estado','fecha_fin','resumen']))
 THEN RAISE EXCEPTION 'Identidad e historia del ciclo GIS inmutables'; END IF;
 RETURN NEW;
END $$;
