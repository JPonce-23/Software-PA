CREATE FUNCTION fn_gis_candidato_ciclo() RETURNS trigger LANGUAGE plpgsql AS $$
 BEGIN
 IF TG_OP='INSERT' AND NEW.id_ciclo IS NULL THEN
  SELECT r.id_ciclo INTO NEW.id_ciclo FROM importacion_conciliacion_resultado r
  JOIN importacion_conciliacion_ciclo c USING(id_ciclo)
  WHERE r.id_importacion_feature=NEW.id_importacion_feature ORDER BY c.numero_ciclo DESC LIMIT 1;
 END IF;
 IF TG_OP='UPDATE' AND (NEW.id_ciclo<>OLD.id_ciclo OR NOT EXISTS(
  SELECT 1 FROM importacion_conciliacion_resultado r JOIN importacion_conciliacion_ciclo c USING(id_ciclo)
  WHERE r.id_importacion_feature=OLD.id_importacion_feature AND c.numero_ciclo=(
   SELECT max(c2.numero_ciclo) FROM importacion_conciliacion_resultado r2
   JOIN importacion_conciliacion_ciclo c2 USING(id_ciclo) WHERE r2.id_importacion_feature=OLD.id_importacion_feature)
  AND r.id_ciclo=OLD.id_ciclo)) THEN RAISE EXCEPTION 'Candidato histórico inmutable'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER trg_gis_candidato_ciclo BEFORE INSERT OR UPDATE ON importacion_feature_candidato
 FOR EACH ROW EXECUTE FUNCTION fn_gis_candidato_ciclo();
